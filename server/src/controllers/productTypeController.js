const prisma = require('../lib/prisma');
const { ensureProductTypes } = require('../services/productTypes');

const locked = (req, res) => {
  res.status(403).json({ error: 'Product types are generated by the system.' });
};

const getProductTypes = async (req, res) => {
  try {
    const productTypes = await ensureProductTypes(prisma, req.tenantId);
    res.json(productTypes);
  } catch (error) {
    console.error('Fetch product types error:', error);
    res.status(500).json({ error: 'Failed to fetch product types' });
  }
};

module.exports = {
  getProductTypes,
  createProductType: locked,
  updateProductType: locked,
  deleteProductType: locked
};
